def norm_key_line(l):
    return key(l)


RESEQ_ON = False


def artkey(line):
    m = re.match(r"^\s*(\d{1,2})\s*[.．]\s*(\d{1,2})\s*[.．]\s*(\d{1,2})\s*(.*)$", line.strip())
    if not m:
        return None
    return (int(m.group(1)), int(m.group(2)), int(m.group(3)))


def resequence(lines, rep, name):
    """merge_v1_v2.py 会把 v1 的「条文号行」插到错误锚点，导致条文被后来的条文号行
    隔断（v2 的续行仍在原位）。本步骤把乱序的条文号行移回其正确位置。

    判定：若某条文号行之后出现了**编号更小**的条文号行，则该行乱序。
    迁移：插到「第一条编号大于它的条文号行」之前（即其前一条的正文之后）。
    """
    body_end = len(lines)
    for i, l in enumerate(lines):
        if re.match(r"^\s*(本规范用词说明|引用标准名录|条文说明|本规范用词)", l.strip()):
            body_end = i
            break
    keys = [(i, artkey(lines[i])) for i in range(body_end)]
    keys = [(i, k) for i, k in keys if k]
    maxk = None
    flagged = []
    for i, k in keys:
        if maxk is not None and k < maxk:
            flagged.append((i, k))
        else:
            maxk = k
    if not flagged:
        return lines
    # 收集（不断更新）以避免重复移动
    moved = 0
    for i, k in sorted(flagged, key=lambda x: x[1]):
        # 该行可能已因先前移动而改变位置，按内容定位
        try:
            cur = next(j for j, l in enumerate(lines) if artkey(l) == k and j < body_end)
        except StopIteration:
            continue
        txt = lines.pop(cur)
        tgt = next((j for j in range(len(lines)) if artkey(lines[j]) and artkey(lines[j]) > k), None)
        if tgt is None:
            lines.append(txt)
        else:
            lines.insert(tgt, txt)
        moved += 1
    rep.append(f"[{name}] RESEQ 重排乱序条文号行 {moved} 条")
    return lines


def apply(name, lines, rep):
    std = name.split("-")[0].split(" ")[0]

    def std_of(name):
        for tag in ("50352", "55019", "55031", "55037", "JGJ"):
            if tag in name:
                return tag
        return ""

    tag = std_of(name)

    def find(anchor, start=0):
        ka = key(anchor)
        for i in range(start, len(lines)):
            if ka and ka in key(lines[i]):
                return i
        return -1

    # 1) DEL
    for t, text in DEL:
        if t != tag:
            continue
        for i, l in enumerate(lines):
            if l.strip() == text:
                rep.append(f"[{name}] DEL     | {text[:60]}")
                lines.pop(i)
                break
        else:
            rep.append(f"[{name}] !! DEL 未命中 | {text[:60]}")

    # 1b) RESEQ：先把乱序的条文号行归位（其续行本来就在原位）
    #     —— 实测副作用大（术语章会被错误重组），默认关闭，仅 --reseq 时启用
    if RESEQ_ON:
        lines = resequence(lines, rep, name)

    # 2) REPL
    for t, old, new in REPL:
        if t != tag:
            continue
        done = False
        for i, l in enumerate(lines):
            if old in l and old != new:
                lines[i] = l.replace(old, new)
                rep.append(f"[{name}] REPL    | {old[:40]} -> {new[:50]}")
                done = True
                break
        if not done:
            rep.append(f"[{name}] !! REPL 未命中 | {old[:50]}")

    # 2b) REPLLINE
    for t, old, new in REPLLINE + REPLLINE2:
        if t != tag:
            continue
        for i, l in enumerate(lines):
            if l.strip() == old:
                lines[i] = new
                rep.append(f"[{name}] REPLLINE| {old} -> {new}")
                break
        else:
            rep.append(f"[{name}] !! REPLLINE 未命中 | {old}")

    # 3) INS（在锚点后）
    for t, anchor, text in INS:
        if t != tag or text is None:
            continue
        i = find(anchor)
        if i < 0:
            rep.append(f"[{name}] !! INS 锚点未命中 | {anchor[:50]}")
            continue
        local = key("\n".join(lines[max(0, i - 12):i + 13]))
        if key(text) in local:
            rep.append(f"[{name}] SKIP(近邻已存在) | {text[:60]}")
            continue
        lines.insert(i + 1, text)
        rep.append(f"[{name}] +@{i + 1:5d}   | {text[:66]}")

    # 4) INSB（在锚点前）
    for t, anchor, text in INSB:
        if t != tag:
            continue
        i = find(anchor)
        if i < 0:
            rep.append(f"[{name}] !! INSB 锚点未命中 | {anchor[:50]}")
            continue
        lines.insert(i, text)
        rep.append(f"[{name}] +@{i:5d}前 | {text[:66]}")

    # 4c) MOVB / MOVB2（修正错序：先摘出行块，再插到锚点之前）
    for t, texts, anchor in MOVB + MOVB2:
        if t != tag:
            continue
        block = []
        for text in texts:
            try:
                j = next(i for i, l in enumerate(lines) if l.strip() == text)
            except StopIteration:
                rep.append(f"[{name}] !! MOVB 未找到源行 | {text[:50]}")
                continue
            block.append(lines.pop(j))
        if not block:
            continue
        i = find(anchor)
        if i < 0:
            rep.append(f"[{name}] !! MOVB 锚点未命中，行块回填末尾 | {anchor[:40]}")
            lines.extend(block)
            continue
        for off, b in enumerate(block):
            lines.insert(i + off, b)
        rep.append(f"[{name}] MOVB@{i:5d}前 | " + " / ".join(b[:26] for b in block))

    # 5) MOV（修正错序：先摘出行块，再插到锚点之后）
    for t, texts, anchor in MOV:
        if t != tag:
            continue
        block = []
        for text in texts:
            try:
                j = next(i for i, l in enumerate(lines) if l.strip() == text)
            except StopIteration:
                rep.append(f"[{name}] !! MOV 未找到源行 | {text[:50]}")
                continue
            block.append(lines.pop(j))
        if not block:
            continue
        i = find(anchor)
        if i < 0:
            rep.append(f"[{name}] !! MOV 锚点未命中，行块回填末尾 | {anchor[:40]}")
            lines.extend(block)
            continue
        for off, b in enumerate(block):
            lines.insert(i + 1 + off, b)
        rep.append(f"[{name}] MOV->@{i + 1:5d} | " + " / ".join(b[:26] for b in block))

    # 6) DELAFTER
    for t, anchor, text in DELAFTER:
        if t != tag:
            continue
        i = find(anchor)
        if i >= 0 and i + 1 < len(lines) and lines[i + 1].strip() == text:
            rep.append(f"[{name}] DELAFT  | {text[:60]}")
            lines.pop(i + 1)
        else:
            rep.append(f"[{name}] !! DELAFTER 未命中 | {text[:50]}")

    return lines


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--src", default="../ocr_v3")
    ap.add_argument("--out", default="../ocr_v4")
    ap.add_argument("--report", default="../ocr_v4/_build_report.txt")
    ap.add_argument("--reseq", action="store_true", help="启用 RESEQ 乱序重排（实测副作用大，默认关闭）")
    a = ap.parse_args()
    global RESEQ_ON
    RESEQ_ON = a.reseq
    os.makedirs(a.out, exist_ok=True)
    rep = []
    for name in sorted(os.listdir(a.src)):
        if not name.endswith(".md"):
            continue
        lines = open(os.path.join(a.src, name), encoding="utf-8").read().splitlines()
        n0 = len(lines)
        lines = apply(name, lines, rep)
        open(os.path.join(a.out, name), "w", encoding="utf-8", newline="\n").write("\n".join(lines) + "\n")
        print(f"{name[:36]:38s} {n0:5d} -> {len(lines):5d} 行")
    open(a.report, "w", encoding="utf-8", newline="\n").write("\n".join(rep) + "\n")
    print("明细 ->", a.report)


if __name__ == "__main__":
    main()
